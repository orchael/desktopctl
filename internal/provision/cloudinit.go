package provision

import (
	"bytes"
	"embed"
	"strings"
	"text/template"
)

//go:embed ansible/desktop-setup/*
var ansibleFS embed.FS

const (
	AIAgentBridgeVersion = "v0.1.0"
	DefaultNoVNCHTTPPort  = 8080
	DefaultNoVNCHTTPSPort = 8443
)

// BootstrapConfig holds the parameters for rendering the cloud-init user-data.
type BootstrapConfig struct {
	DesktopID            string
	Hostname             string // FQDN used for certbot cert and novnc-desktop cert path
	GitHubOwner          string
	Repos                []string
	WorkspacePath        string
	BridgePort           int
	NoVNCHTTPPort        int
	NoVNCHTTPSPort       int
	CertbotEmail         string
	PATSecretPath        string
	AWSRegion            string
	Environment          string
	PackagesPreInstalled bool
	AnsiblePlaybook      string // embedded ansible/desktop-setup/playbook.yml content
	AnsibleInventory     string // embedded ansible/desktop-setup/inventory.ini content
}

const cloudInitTemplate = `#cloud-config
# ai-desktops bootstrap — desktop {{ .DesktopID }}
# Generated by ai-desktops CLI

{{- if not .PackagesPreInstalled}}
package_update: true
package_upgrade: false

packages:
  - git
  - docker.io
  - tmux
  - curl
  - wget
  - unzip
  - ca-certificates
  - apt-transport-https
  - gnupg
  - lsb-release
  - software-properties-common
  - snapd
  - awscli
  - certbot
  - python3-certbot-dns-route53
  - ansible
{{- end}}

write_files:
  - path: /opt/ai-desktops/ansible/playbook.yml
    owner: root:root
    permissions: "0644"
    content: |
{{ .AnsiblePlaybook | indent 6 }}
  - path: /opt/ai-desktops/ansible/inventory.ini
    owner: root:root
    permissions: "0644"
    content: |
{{ .AnsibleInventory | indent 6 }}

runcmd:
  # --- run desktop-setup ansible playbook ---
  - ansible-playbook /opt/ai-desktops/ansible/playbook.yml -i /opt/ai-desktops/ansible/inventory.ini

  # --- system setup ---
  - systemctl enable docker
  - systemctl start docker
  - usermod -aG docker ubuntu

{{- if not .PackagesPreInstalled}}
  # --- nvim (via snap) ---
  - snap install nvim --classic
{{- end}}

  # --- workspace ---
  - mkdir -p {{ .WorkspacePath }}
  - chown ubuntu:ubuntu {{ .WorkspacePath }}

  # --- ai-desktops runtime directory ---
  - mkdir -p /opt/ai-desktops
  - chown ubuntu:ubuntu /opt/ai-desktops

{{- if .PackagesPreInstalled}}
  # --- TLS + nginx + /app/ route via ai-desktops-setup-tls ---
  # Reconfigures ports (80→{{ .NoVNCHTTPPort }}, 443→{{ .NoVNCHTTPSPort }}), obtains a
  # Let's Encrypt cert via DNS-01 (Route53), wires it into the novnc nginx
  # config, and adds the /app/ proxy location for the ai-desktops web app.
  - |
    CERTBOT_DOMAIN="{{ .Hostname }}" \
    CERTBOT_EMAIL="{{ .CertbotEmail }}" \
    NOVNC_HTTP_PORT="{{ .NoVNCHTTPPort }}" \
    NOVNC_HTTPS_PORT="{{ .NoVNCHTTPSPort }}" \
    /usr/local/bin/ai-desktops-setup-tls
  - "systemctl enable novnc-desktop 2>/dev/null || echo \"WARNING: novnc-desktop.service not found\""
  - "systemctl start novnc-desktop 2>/dev/null || echo \"WARNING: could not start novnc-desktop\""
{{- else}}
  # --- TLS certificate via Route53 DNS-01 (no port 80 required) ---
  - |
    if command -v certbot &>/dev/null; then
      certbot certonly --dns-route53 --non-interactive --agree-tos --email {{ .CertbotEmail }} -d {{ .Hostname }} || echo "WARNING: certbot failed"
      systemctl enable certbot.timer 2>/dev/null || true
      systemctl start certbot.timer 2>/dev/null || true
    else
      echo "ERROR: certbot not found"
      exit 1
    fi
{{- end}}

{{- if not .PackagesPreInstalled}}
  # --- ai-agent-bridge {{ .BridgeVersion }} ---
  - curl -fsSL https://raw.githubusercontent.com/orchael/ai-agent-bridge/{{ .BridgeVersion }}/install.sh | bash -s -- --bind 127.0.0.1 --port {{ .BridgePort }} || echo "WARNING: ai-agent-bridge installation failed"
{{- end}}
  - |
    if systemctl list-unit-files | grep -q ai-agent-bridge.service; then
      systemctl enable ai-agent-bridge
      systemctl start ai-agent-bridge
    else
      echo "WARNING: ai-agent-bridge.service not found - bridge will not be available"
    fi

  # --- retrieve github PAT and clone repos ---
  - |
    set -e
    REGION="{{ .AWSRegion }}"
    PAT_SECRET="{{ .PATSecretPath }}"
    WORKSPACE="{{ .WorkspacePath }}"
    OWNER="{{ .GitHubOwner }}"

    # Retrieve PAT from SSM Parameter Store, falling back to Secrets Manager.
    PAT=$(aws ssm get-parameter \
      --region "$REGION" \
      --name "$PAT_SECRET" \
      --with-decryption \
      --query Parameter.Value \
      --output text 2>/dev/null) || \
    PAT=$(aws secretsmanager get-secret-value \
      --region "$REGION" \
      --secret-id "$PAT_SECRET" \
      --query SecretString \
      --output text)

    if [ -z "$PAT" ]; then
      echo "ERROR: could not retrieve GitHub PAT from $PAT_SECRET" >&2
      exit 1
    fi

    # Write credentials to .netrc so the PAT never appears in process args or git URLs.
    printf 'machine github.com\nlogin x-access-token\npassword %s\n' "$PAT" > /root/.netrc
    chmod 600 /root/.netrc
    unset PAT

    # Clone repositories
{{ range .Repos }}
    REPO_URL="{{ . }}"
    REPO_NAME=$(basename "$REPO_URL" .git)
    REPO_OWNER=$(echo "$REPO_URL" | sed 's|.*github.com/||' | cut -d/ -f1)

    # Enforce owner boundary
    if [ "$REPO_OWNER" != "$OWNER" ]; then
      echo "ERROR: repo $REPO_URL owner $REPO_OWNER does not match desktop owner $OWNER" >&2
      exit 1
    fi

    DEST="$WORKSPACE/$REPO_NAME"
    if [ ! -d "$DEST/.git" ]; then
      git clone "https://github.com/${OWNER}/${REPO_NAME}.git" "$DEST"
      chown -R ubuntu:ubuntu "$DEST"
    fi
{{ end }}
    # Remove .netrc credentials after cloning.
    rm -f /root/.netrc

  # --- write desktop metadata ---
  - |
    {
      printf 'DESKTOP_ID="%s"\n' "{{ .DesktopID }}"
      printf 'GITHUB_OWNER="%s"\n' "{{ .GitHubOwner }}"
      printf 'WORKSPACE="%s"\n' "{{ .WorkspacePath }}"
      printf 'ENVIRONMENT="%s"\n' "{{ .Environment }}"
      printf 'BRIDGE_PORT="%s"\n' "{{ .BridgePort }}"
    } > /opt/ai-desktops/desktop.env
    chmod 600 /opt/ai-desktops/desktop.env

final_message: "ai-desktops bootstrap complete for {{ .DesktopID }}"
`

// RenderCloudInit renders the cloud-init user-data for the given config.
func RenderCloudInit(cfg *BootstrapConfig) (string, error) {
	if cfg.WorkspacePath == "" {
		cfg.WorkspacePath = "/workspace"
	}
	if cfg.BridgePort == 0 {
		cfg.BridgePort = 9445
	}
	if cfg.NoVNCHTTPPort == 0 {
		cfg.NoVNCHTTPPort = DefaultNoVNCHTTPPort
	}
	if cfg.NoVNCHTTPSPort == 0 {
		cfg.NoVNCHTTPSPort = DefaultNoVNCHTTPSPort
	}
	if cfg.CertbotEmail == "" {
		cfg.CertbotEmail = "admin@orchael.ai"
	}

	// Read embedded Ansible files
	playbookBytes, err := ansibleFS.ReadFile("ansible/desktop-setup/playbook.yml")
	if err != nil {
		return "", err
	}
	cfg.AnsiblePlaybook = string(playbookBytes)

	inventoryBytes, err := ansibleFS.ReadFile("ansible/desktop-setup/inventory.ini")
	if err != nil {
		return "", err
	}
	cfg.AnsibleInventory = string(inventoryBytes)

	// Expose version constants to the template via a wrapper.
	type templateData struct {
		*BootstrapConfig
		BridgeVersion string
	}
	data := templateData{
		BootstrapConfig: cfg,
		BridgeVersion:   AIAgentBridgeVersion,
	}

	funcMap := template.FuncMap{
		"indent": func(spaces int, text string) string {
			lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
			indent := strings.Repeat(" ", spaces)
			for i, line := range lines {
				if line != "" {
					lines[i] = indent + line
				}
			}
			return strings.Join(lines, "\n")
		},
	}
	tmpl, err := template.New("cloud-init").Funcs(funcMap).Parse(cloudInitTemplate)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", err
	}
	return buf.String(), nil
}
