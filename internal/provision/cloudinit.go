// RenderCloudInit renders the cloud-init user-data for the given config.
func RenderCloudInit(cfg *BootstrapConfig) (string, error) {
	if cfg.WorkspacePath == "" {
		cfg.WorkspacePath = "/workspace"
	}
	if cfg.WorkspaceMode == "" {
		cfg.WorkspaceMode = "local"
	}
	if cfg.BridgePort == 0 {
		cfg.BridgePort = 9445
	}
	if cfg.NoVNCHTTPPort == 0 {
		cfg.NoVNCHTTPPort = DefaultNoVNCHTTPPort
	}
	if cfg.NoVNCHTTPSPort == 0 {
		cfg.NoVNCHTTPSPort = DefaultNoVNCHTTPSPort
	}
	if cfg.CertbotEmail == "" {
		cfg.CertbotEmail = "admin@orchael.ai"
	}
	var desktopProfile DesktopProfileReference
	if cfg.DesktopProfile != "" {
		var err error
		desktopProfile, err = ParseDesktopProfileReference(cfg.DesktopProfile)
		if err != nil {
			return "", err
		}
	}
	var err error
	cfg.NPMGitHubScopes, err = NormalizeNPMGitHubScopes(cfg.NPMGitHubScopes)
	if err != nil {
		return "", err
	}

	// Pre-compute AVD vars JSON (base64-encoded) for safe shell embedding in cloud-init.
	// Base64 avoids heredoc indentation issues and shell quote escaping.
	var avdsJSONB64 string
	if len(cfg.AVDs) > 0 {
		type avdVar struct {
			Name   string `json:"name"`
			Image  string `json:"image"`
			Device string `json:"device,omitempty"`
		}
		vars := struct {
			AVDs []avdVar `json:"avds"`
		}{}
		for _, a := range cfg.AVDs {
			vars.AVDs = append(vars.AVDs, avdVar{Name: a.Name, Image: a.Image, Device: a.Device})
		}
		b, err := json.Marshal(vars)
		if err != nil {
			return "", err
		}
		avdsJSONB64 = base64.StdEncoding.EncodeToString(b)
	}
	var stepCAClientsJSONB64 string
	if len(cfg.StepCAClients) > 0 {
		type clientVar struct {
			Issuer   string `json:"issuer"`
			KeyPath  string `json:"key_path"`
			Required bool   `json:"required,omitempty"`
		}
		clients := make([]clientVar, 0, len(cfg.StepCAClients))
		for _, c := range cfg.StepCAClients {
			clients = append(clients, clientVar{
				Issuer:   c.Issuer,
				KeyPath:  "/home/ubuntu/.config/bridgectl/certs/jwt-clients/" + c.Issuer + ".pub",
				Required: c.Required,
			})
		}
		b, err := json.Marshal(clients)
		if err != nil {
			return "", err
		}
		stepCAClientsJSONB64 = base64.StdEncoding.EncodeToString(b)
	}

	// Expose version constants and pre-computed fields to the template via a wrapper.
	type templateData struct {
		*BootstrapConfig
		BridgeVersion            string
		BridgePackageVersion     string
		AVDsJSONB64              string
		StepCAClientsJSONB64     string
		DesktopProfileOwner      string
		DesktopProfileRepository string
		DesktopProfilePath       string
		CodexHomeConfigScript    string
	}
	data := templateData{
		BootstrapConfig:          cfg,
		BridgeVersion:            BridgectlVersion,
		BridgePackageVersion:     strings.TrimPrefix(BridgectlVersion, "v"),
		AVDsJSONB64:              avdsJSONB64,
		StepCAClientsJSONB64:     stepCAClientsJSONB64,
		DesktopProfileOwner:      desktopProfile.Owner,
		DesktopProfileRepository: desktopProfile.Repository,
		DesktopProfilePath:       desktopProfile.Path,
		CodexHomeConfigScript:    codexHomeConfigScript,
	}

	funcMap := template.FuncMap{
		"b64": func(text string) string {
			return base64.StdEncoding.EncodeToString([]byte(text))
		},
		"indent": func(spaces int, text string) string {
			lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
			indent := strings.Repeat(" ", spaces)
			for i, line := range lines {
				if line != "" {
					lines[i] = indent + line
				}
			}
			return strings.Join(lines, "\n")
		},
	}
	tmpl, err := template.New("cloud-init").Funcs(funcMap).Parse(cloudInitTemplate)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", err
	}
	return buf.String(), nil
}
