package provision

import (
	"bytes"
	"embed"
	"strings"
	"text/template"
)

//go:embed ansible/desktop-setup/*
var ansibleFS embed.FS

const (
	AIAgentBridgeVersion  = "v0.2.0"
	DefaultNoVNCHTTPPort  = 8080
	DefaultNoVNCHTTPSPort = 8443
)

// BootstrapConfig holds the parameters for rendering the cloud-init user-data.
type BootstrapConfig struct {
	DesktopID            string
	Hostname             string // FQDN used for certbot cert and novnc-desktop cert path
	GitHubOwner          string
	Repos                []string
	WorkspacePath        string
	BridgePort           int
	NoVNCHTTPPort        int
	NoVNCHTTPSPort       int
	CertbotEmail         string
	GitHubSecretPath     string // AWS Secrets Manager path: /ai-desktops/<owner>/github
	AgentSecretPath      string // AWS Secrets Manager path: /ai-desktops/<owner>/agents
	AWSRegion            string
	Environment          string
	PackagesPreInstalled bool
	SSHPublicKey         string // ed25519/RSA public key injected into ubuntu's authorized_keys
	AnsiblePlaybook      string // embedded ansible/desktop-setup/playbook.yml content
	AnsibleInventory     string // embedded ansible/desktop-setup/inventory.ini content
}

const cloudInitTemplate = `#cloud-config
# ai-desktops bootstrap — desktop {{ .DesktopID }}
# Generated by ai-desktops CLI
{{- if .SSHPublicKey}}

ssh_authorized_keys:
  - {{ .SSHPublicKey }}
{{- end}}

{{- if not .PackagesPreInstalled}}
package_update: true
package_upgrade: false

packages:
  - git
  - docker.io
  - tmux
  - curl
  - wget
  - unzip
  - ca-certificates
  - apt-transport-https
  - gnupg
  - lsb-release
  - software-properties-common
  - snapd
  - awscli
  - certbot
  - python3-certbot-dns-route53
  - ansible
  - gh
{{- end}}

write_files:
  - path: /opt/ai-desktops/ansible/playbook.yml
    owner: root:root
    permissions: "0644"
    content: |
{{ .AnsiblePlaybook | indent 6 }}
  - path: /opt/ai-desktops/ansible/inventory.ini
    owner: root:root
    permissions: "0644"
    content: |
{{ .AnsibleInventory | indent 6 }}

runcmd:
  # --- run desktop-setup ansible playbook ---
  - ansible-playbook /opt/ai-desktops/ansible/playbook.yml -i /opt/ai-desktops/ansible/inventory.ini

  # --- system setup ---
  - systemctl enable docker
  - systemctl start docker
  - usermod -aG docker ubuntu

{{- if not .PackagesPreInstalled}}
  # --- nvim (via snap) ---
  - snap install nvim --classic
{{- end}}

  # --- workspace ---
  - mkdir -p {{ .WorkspacePath }}
  - chown ubuntu:ubuntu {{ .WorkspacePath }}

  # --- ai-desktops runtime directory ---
  - mkdir -p /opt/ai-desktops
  - chown ubuntu:ubuntu /opt/ai-desktops

{{- if .PackagesPreInstalled}}
  # --- TLS + nginx + /app/ route via ai-desktops-setup-tls ---
  # Reconfigures ports (80→{{ .NoVNCHTTPPort }}, 443→{{ .NoVNCHTTPSPort }}), obtains a
  # Let's Encrypt cert via DNS-01 (Route53), wires it into the novnc nginx
  # config, and adds the /app/ proxy location for the ai-desktops web app.
  - |
    CERTBOT_DOMAIN="{{ .Hostname }}" \
    CERTBOT_EMAIL="{{ .CertbotEmail }}" \
    NOVNC_HTTP_PORT="{{ .NoVNCHTTPPort }}" \
    NOVNC_HTTPS_PORT="{{ .NoVNCHTTPSPort }}" \
    /usr/local/bin/ai-desktops-setup-tls
  - "systemctl enable novnc-desktop 2>/dev/null || echo \"WARNING: novnc-desktop.service not found\""
  - "systemctl start novnc-desktop 2>/dev/null || echo \"WARNING: could not start novnc-desktop\""
{{- else}}
  # --- TLS certificate via Route53 DNS-01 (no port 80 required) ---
  - |
    if command -v certbot &>/dev/null; then
      certbot certonly --dns-route53 --non-interactive --agree-tos --email {{ .CertbotEmail }} -d {{ .Hostname }} || echo "WARNING: certbot failed"
      systemctl enable certbot.timer 2>/dev/null || true
      systemctl start certbot.timer 2>/dev/null || true
    else
      echo "ERROR: certbot not found"
      exit 1
    fi
{{- end}}

{{- if not .PackagesPreInstalled}}
  # --- ai-agent-bridge {{ .BridgeVersion }} (Docker image; no curl installer available) ---
  # The bridge requires TLS certs and config; pre-install via AMI for full bridge support.
  # Pull the image so it is cached for manual setup later.
  - |
    docker pull ghcr.io/markcallen/ai-agent-bridge:{{ .BridgeVersion }} 2>/dev/null || true
{{- end}}
  - |
    if systemctl list-unit-files | grep -q ai-agent-bridge.service; then
      systemctl enable ai-agent-bridge
      systemctl start ai-agent-bridge
    else
      echo "WARNING: ai-agent-bridge.service not found - bridge will not be available"
    fi

  # --- retrieve GitHub credentials and configure SSH ---
  - |
    (
    set -e
    REGION="{{ .AWSRegion }}"
    SECRET="{{ .GitHubSecretPath }}"
    WORKSPACE="{{ .WorkspacePath }}"
    OWNER="{{ .GitHubOwner }}"

    # Retrieve JSON secret from Secrets Manager
    SECRET_JSON=$(aws secretsmanager get-secret-value \
      --region "$REGION" \
      --secret-id "$SECRET" \
      --query SecretString \
      --output text)

    if [ -z "$SECRET_JSON" ]; then
      echo "ERROR: could not retrieve secret from $SECRET" >&2
      exit 1
    fi

    GITHUB_TOKEN=$(printf '%s\n' "$SECRET_JSON" | python3 -c "import json,sys; print(json.load(sys.stdin)['github_token'])")
    SSH_KEY=$(printf '%s\n' "$SECRET_JSON" | python3 -c "import json,sys; print(json.load(sys.stdin)['ssh_private_key'])")
    unset SECRET_JSON

    # Install SSH private key for github.com
    install -d -o ubuntu -g ubuntu -m 700 /home/ubuntu/.ssh
    printf '%s\n' "$SSH_KEY" > /home/ubuntu/.ssh/github_ed25519
    chmod 600 /home/ubuntu/.ssh/github_ed25519
    chown ubuntu:ubuntu /home/ubuntu/.ssh/github_ed25519
    unset SSH_KEY

    # Configure SSH to use the key for github.com
    printf 'Host github.com\n  IdentityFile ~/.ssh/github_ed25519\n  StrictHostKeyChecking accept-new\n  User git\n' \
      > /home/ubuntu/.ssh/config
    chmod 600 /home/ubuntu/.ssh/config
    chown ubuntu:ubuntu /home/ubuntu/.ssh/config

    # Authenticate gh CLI as ubuntu user (non-fatal: token may lack read:org scope)
    printf '%s\n' "$GITHUB_TOKEN" | sudo -u ubuntu gh auth login --with-token || echo "WARNING: gh auth login failed - gh CLI may not be fully authenticated"

    # Configure git commit identity
    sudo -u ubuntu git config --global user.name  "AI Desktop ({{ .DesktopID }})"
    sudo -u ubuntu git config --global user.email "desktop-{{ .DesktopID }}@noreply.github.com"

    unset GITHUB_TOKEN
    )

{{- if .AgentSecretPath}}
  # --- retrieve AI provider API keys and write agents.env ---
  - |
    (
    set -e
    REGION="{{ .AWSRegion }}"
    AGENT_SECRET="{{ .AgentSecretPath }}"

    # Retrieve JSON secret from Secrets Manager
    AGENT_JSON=$(aws secretsmanager get-secret-value \
      --region "$REGION" \
      --secret-id "$AGENT_SECRET" \
      --query SecretString \
      --output text 2>/dev/null) || { echo "WARNING: could not retrieve agent secret from $AGENT_SECRET" >&2; exit 0; }

    if [ -z "$AGENT_JSON" ]; then
      echo "WARNING: agent secret $AGENT_SECRET was empty — agents.env not written" >&2
      exit 0
    fi

    # Write env file from JSON keys
    mkdir -p /etc/ai-agent-bridge
    printf '%s\n' "$AGENT_JSON" | python3 -c "import json,sys; d=json.load(sys.stdin); print('\n'.join(f'{k}={v}' for k,v in d.items() if v))" > /etc/ai-agent-bridge/agents.env
    chmod 600 /etc/ai-agent-bridge/agents.env
    chown root:root /etc/ai-agent-bridge/agents.env
    unset AGENT_JSON

    # Restart the bridge so it picks up the new keys
    if systemctl is-active --quiet ai-agent-bridge 2>/dev/null; then
      systemctl restart ai-agent-bridge
    fi
    )
{{- end}}

  # --- suppress Claude Code first-run onboarding (blocks non-interactive use) ---
  - |
    install -d -o ubuntu -g ubuntu -m 700 /home/ubuntu/.claude
    if [ ! -f /home/ubuntu/.claude.json ]; then
      printf '{"hasCompletedOnboarding":true}\n' > /home/ubuntu/.claude.json
      chown ubuntu:ubuntu /home/ubuntu/.claude.json
      chmod 600 /home/ubuntu/.claude.json
    fi

  # --- clone repositories ---
{{ range .Repos }}
  - |
    (
    set -e
    OWNER="{{ $.GitHubOwner }}"
    WORKSPACE="{{ $.WorkspacePath }}"
    REPO_URL="{{ . }}"
    REPO_NAME=$(basename "$REPO_URL" .git)
    REPO_OWNER=$(echo "$REPO_URL" | sed 's|.*github\.com[/:]||' | cut -d/ -f1)

    if [ "$REPO_OWNER" != "$OWNER" ]; then
      echo "ERROR: repo $REPO_URL owner $REPO_OWNER does not match desktop owner $OWNER" >&2
      exit 1
    fi

    DEST="$WORKSPACE/$REPO_NAME"
    if [ ! -d "$DEST/.git" ]; then
      sudo -u ubuntu git clone "git@github.com:${OWNER}/${REPO_NAME}.git" "$DEST"
    fi
    )
{{ end }}

  # --- write desktop metadata ---
  - |
    {
      printf 'DESKTOP_ID="%s"\n' "{{ .DesktopID }}"
      printf 'GITHUB_OWNER="%s"\n' "{{ .GitHubOwner }}"
      printf 'WORKSPACE="%s"\n' "{{ .WorkspacePath }}"
      printf 'ENVIRONMENT="%s"\n' "{{ .Environment }}"
      printf 'BRIDGE_PORT="%s"\n' "{{ .BridgePort }}"
    } > /opt/ai-desktops/desktop.env
    chgrp ubuntu /opt/ai-desktops/desktop.env
    chmod 640 /opt/ai-desktops/desktop.env

final_message: "ai-desktops bootstrap complete for {{ .DesktopID }}"
`

// RenderCloudInit renders the cloud-init user-data for the given config.
func RenderCloudInit(cfg *BootstrapConfig) (string, error) {
	if cfg.WorkspacePath == "" {
		cfg.WorkspacePath = "/workspace"
	}
	if cfg.BridgePort == 0 {
		cfg.BridgePort = 9445
	}
	if cfg.NoVNCHTTPPort == 0 {
		cfg.NoVNCHTTPPort = DefaultNoVNCHTTPPort
	}
	if cfg.NoVNCHTTPSPort == 0 {
		cfg.NoVNCHTTPSPort = DefaultNoVNCHTTPSPort
	}
	if cfg.CertbotEmail == "" {
		cfg.CertbotEmail = "admin@orchael.ai"
	}

	// Read embedded Ansible files
	playbookBytes, err := ansibleFS.ReadFile("ansible/desktop-setup/playbook.yml")
	if err != nil {
		return "", err
	}
	cfg.AnsiblePlaybook = string(playbookBytes)

	inventoryBytes, err := ansibleFS.ReadFile("ansible/desktop-setup/inventory.ini")
	if err != nil {
		return "", err
	}
	cfg.AnsibleInventory = string(inventoryBytes)

	// Expose version constants to the template via a wrapper.
	type templateData struct {
		*BootstrapConfig
		BridgeVersion string
	}
	data := templateData{
		BootstrapConfig: cfg,
		BridgeVersion:   AIAgentBridgeVersion,
	}

	funcMap := template.FuncMap{
		"indent": func(spaces int, text string) string {
			lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
			indent := strings.Repeat(" ", spaces)
			for i, line := range lines {
				if line != "" {
					lines[i] = indent + line
				}
			}
			return strings.Join(lines, "\n")
		},
	}
	tmpl, err := template.New("cloud-init").Funcs(funcMap).Parse(cloudInitTemplate)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", err
	}
	return buf.String(), nil
}
